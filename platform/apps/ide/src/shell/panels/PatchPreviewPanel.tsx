/**
 * Patch Preview Panel
 *
 * Displays AI-generated patches for user review before application.
 * Shows unified diff view with accept/reject actions.
 *
 * Features:
 * - Unified diff visualization
 * - Side-by-side old/new content view
 * - Accept / Reject / Accept All actions
 * - File navigation
 * - Syntax highlighting
 * - Integration with EditorManager for live preview
 *
 * Architecture:
 *   AI Agent → Backend → Patch
 *       │
 *   executionStore.patchPreviews
 *       │
 *   PatchPreviewPanel ← THIS COMPONENT
 *       │
 *   User: Accept → EditorManager.applyPatch()
 *   User: Reject → executionStore.updatePatchStatus()
 */

import { useState, useMemo, useCallback } from 'react';
import { useExecutionStore } from '../../state/executionStore';
import { editorManager, TextPatch } from '../../core/editor/editorManager';
import styles from './PatchPreviewPanel.module.css';

// ========================================
// TYPES
// ========================================

interface PatchPreviewPanelProps {
  taskId?: string;
  onAccept?: (patchId: string) => void;
  onReject?: (patchId: string) => void;
  onAcceptAll?: (patchIds: string[]) => void;
  className?: string;
}

interface DiffLine {
  type: 'add' | 'delete' | 'context';
  oldLineNumber?: number;
  newLineNumber?: number;
  content: string;
}

interface DiffHunk {
  header: string;
  lines: DiffLine[];
  startOld: number;
  startNew: number;
}

// ========================================
// COMPONENT
// ========================================

export function PatchPreviewPanel({
  taskId,
  onAccept,
  onReject,
  onAcceptAll,
  className,
}: PatchPreviewPanelProps) {
  const [selectedPatchId, setSelectedPatchId] = useState<string | null>(null);
  const [viewMode, setViewMode] = useState<'unified' | 'split'>('unified');

  const pendingPatches = useExecutionStore((s) => s.getPendingPatches());
  const updatePatchStatus = useExecutionStore((s) => s.updatePatchStatus);
  const removePatchPreview = useExecutionStore((s) => s.removePatchPreview);

  // Filter patches by task if provided
  const patches = useMemo(() => {
    if (!taskId) return pendingPatches;
    return pendingPatches.filter((p) => p.taskId === taskId);
  }, [pendingPatches, taskId]);

  // Selected patch
  const selectedPatch = useMemo(() => {
    if (selectedPatchId) {
      return patches.find((p) => p.id === selectedPatchId);
    }
    return patches[0] ?? null;
  }, [patches, selectedPatchId]);

  // Parse diff hunks
  const diffHunks = useMemo(() => {
    if (!selectedPatch) return [];
    return parseDiffHunks(selectedPatch.oldContent, selectedPatch.newContent);
  }, [selectedPatch]);

  // Stats
  const stats = useMemo(() => {
    if (!selectedPatch) return { additions: 0, deletions: 0 };
    return calculateDiffStats(selectedPatch.oldContent, selectedPatch.newContent);
  }, [selectedPatch]);

  // Accept patch
  const handleAccept = useCallback((patchId: string) => {
    const patch = patches.find((p) => p.id === patchId);
    if (!patch) return;

    // Create TextPatch from PatchPreview
    const textPatch: TextPatch = {
      filePath: patch.filePath,
      startLine: 1,
      startColumn: 1,
      endLine: patch.oldContent.split('\n').length,
      endColumn: patch.oldContent.split('\n').pop()?.length ?? 1,
      newText: patch.newContent,
      oldText: patch.oldContent,
      source: 'ai',
      patchId: patch.id,
    };

    // Apply via EditorManager
    const success = editorManager.applyPatch(textPatch);

    if (success) {
      updatePatchStatus(patchId, 'applied');
      onAccept?.(patchId);
    } else {
      console.error('[PatchPreview] Failed to apply patch:', patchId);
    }
  }, [patches, updatePatchStatus, onAccept]);

  // Reject patch
  const handleReject = useCallback((patchId: string) => {
    updatePatchStatus(patchId, 'rejected');
    removePatchPreview(patchId);
    onReject?.(patchId);
  }, [updatePatchStatus, removePatchPreview, onReject]);

  // Accept all patches
  const handleAcceptAll = useCallback(() => {
    const pendingIds = patches
      .filter((p) => p.status === 'pending')
      .map((p) => p.id);

    pendingIds.forEach((id) => handleAccept(id));
    onAcceptAll?.(pendingIds);
  }, [patches, handleAccept, onAcceptAll]);

  // No patches
  if (patches.length === 0) {
    return (
      <div className={`${styles.container} ${styles.empty} ${className ?? ''}`}>
        <div className={styles.emptyState}>
          <span className={styles.emptyIcon}>📝</span>
          <p>No pending patches</p>
          <span className={styles.emptyHint}>
            Patches generated by AI will appear here for review
          </span>
        </div>
      </div>
    );
  }

  return (
    <div className={`${styles.container} ${className ?? ''}`}>
      {/* Header */}
      <div className={styles.header}>
        <h3 className={styles.title}>
          Patches <span className={styles.count}>({patches.length})</span>
        </h3>
        <div className={styles.actions}>
          <button
            className={styles.acceptAllButton}
            onClick={handleAcceptAll}
            disabled={patches.length === 0}
          >
            Accept All
          </button>
          <div className={styles.viewToggle}>
            <button
              className={`${styles.viewButton} ${viewMode === 'unified' ? styles.active : ''}`}
              onClick={() => setViewMode('unified')}
            >
              Unified
            </button>
            <button
              className={`${styles.viewButton} ${viewMode === 'split' ? styles.active : ''}`}
              onClick={() => setViewMode('split')}
            >
              Split
            </button>
          </div>
        </div>
      </div>

      {/* File List */}
      <div className={styles.fileList}>
        {patches.map((patch) => (
          <button
            key={patch.id}
            className={`${styles.fileItem} ${
              selectedPatch?.id === patch.id ? styles.selected : ''
            }`}
            onClick={() => setSelectedPatchId(patch.id)}
          >
            <span className={styles.fileName}>{patch.filePath}</span>
            <span className={styles.fileStats}>
              <span className={styles.additions}>+{patch.hunks.length}</span>
            </span>
          </button>
        ))}
      </div>

      {/* Diff View */}
      {selectedPatch && (
        <div className={styles.diffContainer}>
          {/* File Header */}
          <div className={styles.diffHeader}>
            <span className={styles.filePath}>{selectedPatch.filePath}</span>
            <div className={styles.diffStats}>
              <span className={styles.additions}>+{stats.additions}</span>
              <span className={styles.deletions}>-{stats.deletions}</span>
            </div>
          </div>

          {/* Diff Content */}
          <div className={styles.diffContent}>
            {viewMode === 'unified' ? (
              <UnifiedDiffView hunks={diffHunks} />
            ) : (
              <SplitDiffView
                oldContent={selectedPatch.oldContent}
                newContent={selectedPatch.newContent}
              />
            )}
          </div>

          {/* Actions */}
          <div className={styles.patchActions}>
            <button
              className={styles.rejectButton}
              onClick={() => handleReject(selectedPatch.id)}
            >
              Reject
            </button>
            <button
              className={styles.acceptButton}
              onClick={() => handleAccept(selectedPatch.id)}
            >
              Accept
            </button>
          </div>
        </div>
      )}
    </div>
  );
}

// ========================================
// UNIFIED DIFF VIEW
// ========================================

function UnifiedDiffView({ hunks }: { hunks: DiffHunk[] }) {
  return (
    <div className={styles.unifiedDiff}>
      {hunks.map((hunk, hunkIndex) => (
        <div key={hunkIndex} className={styles.hunk}>
          <div className={styles.hunkHeader}>{hunk.header}</div>
          {hunk.lines.map((line, lineIndex) => (
            <div
              key={lineIndex}
              className={`${styles.line} ${styles[line.type]}`}
            >
              <span className={styles.lineNumber}>
                {line.oldLineNumber ?? ''}
              </span>
              <span className={styles.lineNumber}>
                {line.newLineNumber ?? ''}
              </span>
              <span className={styles.linePrefix}>
                {line.type === 'add' ? '+' : line.type === 'delete' ? '-' : ' '}
              </span>
              <span className={styles.lineContent}>{line.content}</span>
            </div>
          ))}
        </div>
      ))}
    </div>
  );
}

// ========================================
// SPLIT DIFF VIEW
// ========================================

function SplitDiffView({
  oldContent,
  newContent,
}: {
  oldContent: string;
  newContent: string;
}) {
  const oldLines = oldContent.split('\n');
  const newLines = newContent.split('\n');

  return (
    <div className={styles.splitDiff}>
      <div className={styles.splitPane}>
        <div className={styles.splitHeader}>Original</div>
        <div className={styles.splitContent}>
          {oldLines.map((line, i) => (
            <div key={i} className={styles.splitLine}>
              <span className={styles.splitLineNumber}>{i + 1}</span>
              <span className={styles.splitLineContent}>{line}</span>
            </div>
          ))}
        </div>
      </div>
      <div className={styles.splitPane}>
        <div className={styles.splitHeader}>Modified</div>
        <div className={styles.splitContent}>
          {newLines.map((line, i) => (
            <div key={i} className={`${styles.splitLine} ${styles.new}`}>
              <span className={styles.splitLineNumber}>{i + 1}</span>
              <span className={styles.splitLineContent}>{line}</span>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}

// ========================================
// HELPERS
// ========================================

function parseDiffHunks(oldContent: string, newContent: string): DiffHunk[] {
  const oldLines = oldContent.split('\n');
  const newLines = newContent.split('\n');

  // Simple diff algorithm (LCS-based would be better for production)
  const hunks: DiffHunk[] = [];
  let currentHunk: DiffHunk = {
    header: '@@ -1,' + oldLines.length + ' +1,' + newLines.length + ' @@',
    lines: [],
    startOld: 1,
    startNew: 1,
  };

  const maxLen = Math.max(oldLines.length, newLines.length);

  for (let i = 0; i < maxLen; i++) {
    const oldLine = oldLines[i];
    const newLine = newLines[i];

    if (oldLine === undefined) {
      // Addition at end
      currentHunk.lines.push({
        type: 'add',
        newLineNumber: i + 1,
        content: newLine,
      });
    } else if (newLine === undefined) {
      // Deletion at end
      currentHunk.lines.push({
        type: 'delete',
        oldLineNumber: i + 1,
        content: oldLine,
      });
    } else if (oldLine === newLine) {
      // Context line
      currentHunk.lines.push({
        type: 'context',
        oldLineNumber: i + 1,
        newLineNumber: i + 1,
        content: oldLine,
      });
    } else {
      // Changed line
      currentHunk.lines.push({
        type: 'delete',
        oldLineNumber: i + 1,
        content: oldLine,
      });
      currentHunk.lines.push({
        type: 'add',
        newLineNumber: i + 1,
        content: newLine,
      });
    }
  }

  hunks.push(currentHunk);
  return hunks;
}

function calculateDiffStats(
  oldContent: string,
  newContent: string
): { additions: number; deletions: number } {
  const oldLines = oldContent.split('\n');
  const newLines = newContent.split('\n');

  // Simple calculation - count lines added/removed
  const additions = Math.max(0, newLines.length - oldLines.length);
  const deletions = Math.max(0, oldLines.length - newLines.length);

  // Count actual changes (simplified)
  let changedLines = 0;
  const maxLen = Math.max(oldLines.length, newLines.length);
  for (let i = 0; i < maxLen; i++) {
    if (oldLines[i] !== newLines[i]) {
      changedLines++;
    }
  }

  return {
    additions: additions + Math.floor(changedLines / 2),
    deletions: deletions + Math.floor(changedLines / 2),
  };
}

export default PatchPreviewPanel;
