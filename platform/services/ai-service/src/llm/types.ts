import { z } from 'zod';

export type LLMProvider = 'openai' | 'anthropic' | 'groq' | 'deepseek' | 'siliconflow' | 'nvidia' | 'xiaomi' | 'openrouter' | 'huggingface' | 'google' | 'mock';

export type LLMTaskType =
  | 'plan'
  | 'codegen'
  | 'qa'
  | 'security'
  | 'chat';

export type LLMComplexity = 'low' | 'medium' | 'high';

export type LLMRole = 'system' | 'user' | 'assistant' | 'tool';

export const LLMMessageSchema = z.object({
  role: z.enum(['system', 'user', 'assistant', 'tool']),
  content: z.string().min(1),
  name: z.string().min(1).optional(),
  toolCallId: z.string().optional(),
});

export type LLMMessage = z.infer<typeof LLMMessageSchema>;

export const LLMCompletionRequestSchema = z.object({
  requestId: z.string().min(1).optional(), // Generated by gateway if missing; used for tracing
  workflowId: z.string().min(1),
  projectId: z.string().min(1),
  agentName: z.string().min(1),
  stepName: z.string().min(1),
  taskType: z.enum(['plan', 'codegen', 'qa', 'security', 'chat']),
  messages: z.array(LLMMessageSchema).min(1),

  complexity: z.enum(['low', 'medium', 'high']).optional(),
  modelHint: z.string().min(1).optional(),
  temperature: z.number().min(0).max(2).optional(),
  maxTokens: z.number().int().positive().optional(),
  tools: z.array(z.any()).optional(), // LLMToolDefinition[] — validated at runtime

  userId: z.string().min(1).optional(),
  orgId: z.string().min(1).optional(),
});

export type LLMCompletionRequest = z.infer<typeof LLMCompletionRequestSchema>;

export const LLMCompletionResponseSchema = z.object({
  requestId: z.string().min(1), // Echoed back for tracing
  provider: z.enum(['openai', 'anthropic', 'groq', 'deepseek', 'siliconflow', 'nvidia', 'xiaomi', 'openrouter', 'huggingface', 'google', 'mock']),
  model: z.string().min(1),
  outputText: z.string(),
  toolCalls: z.array(z.object({
    id: z.string(),
    name: z.string(),
    arguments: z.record(z.any()),
  })).optional(),

  tokensIn: z.number().int().nonnegative(),
  tokensOut: z.number().int().nonnegative(),
  latencyMs: z.number().int().nonnegative(),
  costUsd: z.number().nonnegative(),
  cacheHit: z.boolean(),
});

export type LLMCompletionResponse = z.infer<typeof LLMCompletionResponseSchema>;

// Tool calling types for agent function-calling support
export type LLMToolParameter = {
  type: string;
  description: string;
  enum?: string[];
  default?: unknown;
};

export type LLMToolDefinition = {
  name: string;
  description: string;
  parameters: {
    type: 'object';
    properties: Record<string, LLMToolParameter>;
    required?: string[];
  };
};

export type LLMToolCall = {
  id: string;
  name: string;
  arguments: Record<string, unknown>;
};

// Internal adapter response type (without requestId - gateway adds it)
export type AdapterResponse = {
  provider: LLMProvider;
  model: string;
  outputText: string;
  toolCalls?: LLMToolCall[];
  tokensIn: number;
  tokensOut: number;
  latencyMs: number;
  costUsd: number;
  cacheHit: boolean;
};

export type LLMStreamChunkEvent =
  | {
      type: 'chunk';
      data: {
        textDelta: string;
      };
    }
  | {
      type: 'meta';
      data: {
        provider: LLMProvider;
        model: string;
      };
    }
  | {
      type: 'done';
      data: {
        provider: LLMProvider;
        model: string;
        tokensIn: number;
        tokensOut: number;
        latencyMs: number;
        costUsd: number;
        cacheHit: boolean;
      };
    }
  | {
      type: 'error';
      data: {
        message: string;
        retryable?: boolean;
      };
    };
